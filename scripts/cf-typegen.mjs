// wrangler types 는 로컬 시크릿 파일을 읽어 그 값을 필수 문자열 타입으로 넣는다 (src/server/env.d.ts 의 선택 시크릿과 충돌).
// 시크릿 파일이 없는 임시 폴더에서 설정 사본으로 생성해 어느 머신에서 돌려도 같은 결과가 나오게 한다.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const tmp = mkdtempSync(join(tmpdir(), "avocado-typegen-"));
try {
  const entry = join(root, "src/server/index.ts");
  const config = readFileSync(join(root, "wrangler.jsonc"), "utf8").replace('"src/server/index.ts"', JSON.stringify(entry));
  writeFileSync(join(tmp, "wrangler.jsonc"), config);
  const args = ["wrangler", "types", join(root, "worker-configuration.d.ts"), "-c", join(tmp, "wrangler.jsonc"), "--strict-vars", "false"];
  execFileSync("npx", args, { cwd: root, stdio: "inherit" });
  // 머신마다 달라지는 임시 경로가 헤더에 남지 않게 고정 문구로 바꾼다
  const out = join(root, "worker-configuration.d.ts");
  const lines = readFileSync(out, "utf8").split("\n");
  lines[1] = "// Generated by `npm run cf-typegen` (scripts/cf-typegen.mjs, wrangler types --strict-vars false)";
  writeFileSync(out, lines.join("\n"));
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
